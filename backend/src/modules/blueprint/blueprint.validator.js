/**
 * Planova - Blueprint Validator
 * Joi validation schemas for blueprint endpoints
 */

const Joi = require('joi');

module.exports = {
  createBlueprint: Joi.object({
    title: Joi.string().trim().min(1).max(200).required()
      .messages({ 'any.required': 'Blueprint title is required' }),
    description: Joi.string().trim().max(5000).required()
      .messages({ 'any.required': 'Description is required' }),
    category: Joi.string().optional().allow(null, ''),
    accessTier: Joi.string().valid('free', 'premium', 'professional', 'enterprise').default('free'),
    price: Joi.number().min(0).default(0),
    currency: Joi.string().default('INR'),
    specs: Joi.object({
      builtUpArea: Joi.number().min(0).required(),
      plotAreaRequired: Joi.number().min(0).optional(),
      plotWidth: Joi.number().min(0).optional(),
      plotLength: Joi.number().min(0).optional(),
      floors: Joi.number().min(1).max(50).required(),
      bedrooms: Joi.number().min(0).default(0),
      bathrooms: Joi.number().min(0).default(0),
      livingRooms: Joi.number().min(0).default(0),
      kitchen: Joi.string().valid('open', 'closed', 'modular', 'island', 'l-shaped', 'u-shaped', 'galley').default('open'),
      parking: Joi.string().valid('covered', 'open', 'basement', 'carport', 'none').default('none'),
      garage: Joi.number().min(0).default(0),
      style: Joi.string().required(),
      constructionType: Joi.string().required(),
      estimatedCost: Joi.number().min(0).optional(),
      estimatedDuration: Joi.number().min(0).optional(),
    }).required(),
    vastu: Joi.object({
      compliant: Joi.boolean().default(false),
      score: Joi.number().min(0).max(100).default(0),
      orientation: Joi.string().valid('north', 'south', 'east', 'west', 'northeast', 'northwest', 'southeast', 'southwest'),
      notes: Joi.string().max(1000).allow('', null),
    }).optional(),
    materials: Joi.object({
      cementBags: Joi.number().min(0).default(0),
      steelTons: Joi.number().min(0).default(0),
      bricks: Joi.number().min(0).default(0),
      sandCubicFeet: Joi.number().min(0).default(0),
      aggregateCubicFeet: Joi.number().min(0).default(0),
      flooringArea: Joi.number().min(0).default(0),
      paintArea: Joi.number().min(0).default(0),
      tilesArea: Joi.number().min(0).default(0),
      windows: Joi.number().min(0).default(0),
      doors: Joi.number().min(0).default(0),
      electricalPoints: Joi.number().min(0).default(0),
      plumbingPoints: Joi.number().min(0).default(0),
      customMaterials: Joi.array().items(Joi.object({
        name: Joi.string(),
        quantity: Joi.number(),
        unit: Joi.string(),
        estimatedCost: Joi.number(),
      })),
    }).optional(),
    sustainability: Joi.object({
      score: Joi.number().min(0).max(100).default(0),
      features: Joi.array().items(Joi.string()),
      energyRating: Joi.string().valid('A+', 'A', 'B', 'C', 'D', 'E', '').allow(null),
      greenCertification: Joi.string().valid('griha', 'igbc', 'leed', 'breeam', 'none', '').allow(null),
      estimatedEnergySavings: Joi.number().min(0).max(100),
    }).optional(),
    files: Joi.object({
      images: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        thumbnailUrl: Joi.string().uri().allow(''),
        alt: Joi.string().allow(''),
        isPrimary: Joi.boolean(),
        caption: Joi.string().allow(''),
      })),
      floorPlans: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        floor: Joi.number(),
      })),
      cadFiles: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        format: Joi.string(),
        fileSize: Joi.number(),
      })),
      model3d: Joi.object({
        url: Joi.string().uri(),
        thumbnailUrl: Joi.string().uri().allow(''),
        format: Joi.string(),
        fileSize: Joi.number(),
      }),
      documents: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        type: Joi.string(),
        fileSize: Joi.number(),
      })),
    }).optional(),
    location: Joi.object({
      city: Joi.string().allow('', null),
      state: Joi.string().allow('', null),
      country: Joi.string().default('India'),
      suitableClimate: Joi.array().items(Joi.string()),
    }).optional(),
    tags: Joi.array().items(Joi.string().trim()).optional(),
    metaTitle: Joi.string().max(60).allow('', null),
    metaDescription: Joi.string().max(160).allow('', null),
  }),

  updateBlueprint: Joi.object({
    title: Joi.string().trim().min(1).max(200),
    description: Joi.string().trim().max(5000),
    category: Joi.string().allow(null, ''),
    accessTier: Joi.string().valid('free', 'premium', 'professional', 'enterprise'),
    price: Joi.number().min(0),
    currency: Joi.string(),
    specs: Joi.object({
      builtUpArea: Joi.number().min(0),
      plotAreaRequired: Joi.number().min(0),
      plotWidth: Joi.number().min(0),
      plotLength: Joi.number().min(0),
      floors: Joi.number().min(1).max(50),
      bedrooms: Joi.number().min(0),
      bathrooms: Joi.number().min(0),
      livingRooms: Joi.number().min(0),
      kitchen: Joi.string().valid('open', 'closed', 'modular', 'island', 'l-shaped', 'u-shaped', 'galley'),
      parking: Joi.string().valid('covered', 'open', 'basement', 'carport', 'none'),
      garage: Joi.number().min(0),
      style: Joi.string(),
      constructionType: Joi.string(),
      estimatedCost: Joi.number().min(0),
      estimatedDuration: Joi.number().min(0),
    }),
    vastu: Joi.object({
      compliant: Joi.boolean(),
      score: Joi.number().min(0).max(100),
      orientation: Joi.string().valid('north', 'south', 'east', 'west', 'northeast', 'northwest', 'southeast', 'southwest'),
      notes: Joi.string().max(1000).allow('', null),
    }),
    materials: Joi.object({
      cementBags: Joi.number().min(0),
      steelTons: Joi.number().min(0),
      bricks: Joi.number().min(0),
      sandCubicFeet: Joi.number().min(0),
      aggregateCubicFeet: Joi.number().min(0),
      flooringArea: Joi.number().min(0),
      paintArea: Joi.number().min(0),
      tilesArea: Joi.number().min(0),
      windows: Joi.number().min(0),
      doors: Joi.number().min(0),
      electricalPoints: Joi.number().min(0),
      plumbingPoints: Joi.number().min(0),
      customMaterials: Joi.array().items(Joi.object({
        name: Joi.string(),
        quantity: Joi.number(),
        unit: Joi.string(),
        estimatedCost: Joi.number(),
      })),
    }),
    sustainability: Joi.object({
      score: Joi.number().min(0).max(100),
      features: Joi.array().items(Joi.string()),
      energyRating: Joi.string().valid('A+', 'A', 'B', 'C', 'D', 'E', '').allow(null),
      greenCertification: Joi.string().valid('griha', 'igbc', 'leed', 'breeam', 'none', '').allow(null),
      estimatedEnergySavings: Joi.number().min(0).max(100),
    }),
    files: Joi.object({
      images: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        thumbnailUrl: Joi.string().uri().allow(''),
        alt: Joi.string().allow(''),
        isPrimary: Joi.boolean(),
        caption: Joi.string().allow(''),
      })),
      floorPlans: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        floor: Joi.number(),
      })),
      cadFiles: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        format: Joi.string(),
        fileSize: Joi.number(),
      })),
      documents: Joi.array().items(Joi.object({
        url: Joi.string().uri(),
        name: Joi.string(),
        type: Joi.string(),
        fileSize: Joi.number(),
      })),
    }),
    location: Joi.object({
      city: Joi.string().allow('', null),
      state: Joi.string().allow('', null),
      country: Joi.string(),
      suitableClimate: Joi.array().items(Joi.string()),
    }),
    tags: Joi.array().items(Joi.string().trim()),
    metaTitle: Joi.string().max(60).allow('', null),
    metaDescription: Joi.string().max(160).allow('', null),
  }).min(1).messages({ 'object.min': 'At least one field must be provided for update' }),
};

